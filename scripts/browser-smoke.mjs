import {chromium} from '@playwright/test';
import fs from 'node:fs/promises';
await fs.mkdir('artifacts',{recursive:true});
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
page.on('response',r=>{if(r.status()>=400)errors.push(`${r.status()} ${r.url()}`);});
await page.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle'});
await page.waitForFunction(()=>window.__CRASH__,null,{timeout:30000});
await page.screenshot({path:'artifacts/01-menu.png'});
console.log('MENU',await page.locator('body').innerText());
await page.getByRole('button',{name:/开始|出发|驶入|开撞/}).first().click();
await page.waitForTimeout(6500);
await page.keyboard.press('Space');await page.waitForTimeout(600);
await page.screenshot({path:'artifacts/02-first-crash.png'});
console.log('FIRST_CRASH',await page.evaluate(()=>{const s=window.__CRASH__.snapshot();return {phase:s.phase,time:s.time,score:s.score,combo:s.combo,crashes:s.crashes,player:s.entities.find(e=>e.player),stats:window.__CRASH__.stats()};}));
await page.keyboard.press('KeyE');await page.waitForTimeout(250);await page.screenshot({path:'artifacts/03-mechanisms.png'});await page.keyboard.press('Digit2');
await page.keyboard.down('Space');await page.waitForTimeout(16000);await page.keyboard.up('Space');
await page.screenshot({path:'artifacts/04-chaos.png'});
console.log('CHAOS',await page.evaluate(()=>{const s=window.__CRASH__.snapshot();return {time:s.time,score:s.score,combo:s.combo,best:s.bestCombo,crashes:s.crashes,entities:s.entities.length,interventions:s.interventions,stats:window.__CRASH__.stats()};}));
await page.keyboard.press('Escape');const t=await page.evaluate(()=>window.__CRASH__.snapshot().time);await page.waitForTimeout(500);const t2=await page.evaluate(()=>window.__CRASH__.snapshot().time);console.log('PAUSE',t===t2);
await page.screenshot({path:'artifacts/05-pause.png'});await page.keyboard.press('Escape');
await page.evaluate(()=>window.__CRASH__.finish());await page.waitForTimeout(800);await page.screenshot({path:'artifacts/06-results.png'});
console.log('RESULT',await page.locator('body').innerText());console.log('ERRORS',errors);
await fs.writeFile('artifacts/browser-smoke.json',JSON.stringify({errors,paused:t===t2,stats:await page.evaluate(()=>window.__CRASH__.stats())},null,2));
await browser.close();
